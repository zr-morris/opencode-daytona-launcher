/*
 * OpenCode + Daytona launcher — Azure Foundry edition (firm internal).
 * ------------------------------------------------------------------
 * Designed to run INSIDE an Azure VNet that can reach a private Azure AI
 * Foundry endpoint. Launches OpenCode Web inside on-demand (self-hosted)
 * Daytona sandboxes, with OpenCode defaulted to the firm's Azure Foundry
 * deployment(s).
 *
 * Auth model (Entra-primary, no API keys for end users):
 *  - App access: lightweight Entra SSO (corporate Microsoft sign-in).
 *  - Foundry calls: Entra managed identity token (no Foundry API key passed),
 *    acquired at sandbox launch and injected into the sandbox. API-key fallback
 *    supported only if the operator opts out of managed identity at setup.
 *
 * Configuration is baked in at install time by `npm run setup` (writes a
 * gitignored .env and an opencode.json). This server just reads that config.
 */

