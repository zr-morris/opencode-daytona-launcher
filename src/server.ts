const ENTRA_TENANT_ID = process.env.ENTRA_TENANT_ID || ''
const ENTRA_CLIENT_ID = process.env.ENTRA_CLIENT_ID || ''
const ENTRA_CLIENT_SECRET = process.env.ENTRA_CLIENT_SECRET || ''
const SSO_ENABLED = Boolean(ENTRA_TENANT_ID && ENTRA_CLIENT_ID && ENTRA_CLIENT_SECRET)
const SESSION_SECRET = process.env.SESSION_SECRET || crypto.randomBytes(32).toString('hex')
const SESSION_TTL_MS = 8 * 60 * 60 * 1000 // 8h
const SESSION_COOKIE = 'ocf_session'
const OAUTH_STATE_COOKIE = 'ocf_oauth_state'
const APP_BASE_URL = (process.env.APP_BASE_URL || '').replace(/\/$/, '')

const RUNNING_STATES = new Set(['started', 'starting', 'running'])

// ---------------------------------------------------------------------------
// opencode.json (generated by setup) — read so we can validate + report.
// We do NOT need to parse it deeply; OpenCode reads it inside the sandbox.
// We DO inject it into the sandbox as OPENCODE_CONFIG_CONTENT so the agent
// defaults to the firm's Azure deployment.
// ---------------------------------------------------------------------------
function loadOpencodeConfig(): any | null {
  const p = path.join(process.cwd(), 'opencode.json')
  try {
    if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf8'))
  } catch (e) {
    console.warn('[config] opencode.json present but unparseable:', (e as any)?.message)
  }
  return null
}

// ---------------------------------------------------------------------------
// Entra SSO: signed-cookie sessions (built-in crypto) + MSAL auth-code flow.
// ---------------------------------------------------------------------------
interface Session { oid: string; name?: string; email?: string; exp: number }

let msal: ConfidentialClientApplication | null = null
if (SSO_ENABLED) {
  msal = new ConfidentialClientApplication({
    auth: {
      clientId: ENTRA_CLIENT_ID,
      authority: `https://login.microsoftonline.com/${ENTRA_TENANT_ID}`,
      clientSecret: ENTRA_CLIENT_SECRET,
    },
  })
}

function b64url(buf: Buffer): string {
  return buf.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
}
function b64urlDecode(s: string): Buffer {
  return Buffer.from(s.replace(/-/g, '+').replace(/_/g, '/'), 'base64')
}
function signSession(sess: Session): string {
  const payload = b64url(Buffer.from(JSON.stringify(sess)))
  const sig = b64url(crypto.createHmac('sha256', SESSION_SECRET).update(payload).digest())
  return payload + '.' + sig
}
function verifySession(token: string): Session | null {
  if (!token || token.indexOf('.') === -1) return null
  const [payload, sig] = token.split('.')
  const expected = b64url(crypto.createHmac('sha256', SESSION_SECRET).update(payload).digest())
  const a = Buffer.from(sig || ''); const b = Buffer.from(expected)
  if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) return null
  try {
    const sess = JSON.parse(b64urlDecode(payload).toString()) as Session
    if (!sess.exp || sess.exp < Date.now()) return null
    return sess
  } catch { return null }
}
function parseCookies(req: Request): Record<string, string> {
  const out: Record<string, string> = {}
  const raw = req.headers.cookie
  if (!raw) return out
  raw.split(';').forEach((p) => {
    const i = p.indexOf('=')
    if (i > -1) out[p.slice(0, i).trim()] = decodeURIComponent(p.slice(i + 1).trim())
  })
  return out
}
function getSession(req: Request): Session | null {
  if (!SSO_ENABLED) return null
  return verifySession(parseCookies(req)[SESSION_COOKIE] || '')
}
function setSessionCookie(res: Response, token: string) {
  res.setHeader('Set-Cookie',
    `${SESSION_COOKIE}=${encodeURIComponent(token)}; HttpOnly; Secure; SameSite=Lax; Path=/; Max-Age=${Math.floor(SESSION_TTL_MS / 1000)}`)
}
function clearSessionCookie(res: Response) {
  res.setHeader('Set-Cookie', `${SESSION_COOKIE}=; HttpOnly; Secure; SameSite=Lax; Path=/; Max-Age=0`)
}
function baseUrl(req: Request): string {
  if (APP_BASE_URL) return APP_BASE_URL
  const proto = (req.headers['x-forwarded-proto'] as string) || req.protocol || 'https'
  const host = (req.headers['x-forwarded-host'] as string) || req.headers.host
  return `${proto}://${host}`
}

// Require an Entra session for protected routes when SSO is enabled.
function requireAuth(req: Request, res: Response, next: NextFunction) {
  if (!SSO_ENABLED) return next()
  const sess = getSession(req)
  if (sess) { (req as any).session = sess; return next() }
  if (req.path.startsWith('/api/')) return res.status(401).json({ error: 'Login required', loginRequired: true })
  return res.redirect('/login')
}

// ---------------------------------------------------------------------------
// Azure Foundry auth: acquire a fresh Entra token (managed identity) per launch.
// ---------------------------------------------------------------------------
let azureCred: DefaultAzureCredential | null = null
function getAzureCred(): DefaultAzureCredential {
  if (!azureCred) azureCred = new DefaultAzureCredential()
  return azureCred
}
async function getFoundryToken(): Promise<string> {
  const tok = await getAzureCred().getToken(AZURE_TOKEN_SCOPE)
  if (!tok || !tok.token) throw new Error('Failed to acquire Entra token for Foundry')
  return tok.token
}

// ---------------------------------------------------------------------------
// Daytona client (self-hosted control plane)
// ---------------------------------------------------------------------------
function daytonaClient(): Daytona {
  const opts: any = { apiKey: DAYTONA_API_KEY }
  if (DAYTONA_API_URL) opts.apiUrl = DAYTONA_API_URL
  if (DAYTONA_TARGET) opts.target = DAYTONA_TARGET
  return new Daytona(opts)
}

