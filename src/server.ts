// ---------------------------------------------------------------------------
// Launch a sandbox running OpenCode Web, defaulted to Azure Foundry.
// ---------------------------------------------------------------------------
app.post('/api/launch', requireAuth, async (req: Request, res: Response) => {
  if (!DAYTONA_API_KEY) return res.status(500).json({ error: 'Daytona is not configured on the server. Run setup.' })
  if (!AZURE_FOUNDRY_BASE_URL || !AZURE_DEFAULT_DEPLOYMENT) {
    return res.status(500).json({ error: 'Azure Foundry is not configured on the server. Run setup.' })
  }
  const wantedName = (req.body && typeof req.body.name === 'string') ? req.body.name.trim().slice(0, 60) : ''

  const daytona = daytonaClient()
  let sandbox: Sandbox | undefined
  try {
    // Acquire a fresh Foundry token per launch (managed identity), unless using a key.
    let foundryToken = ''
    if (AZURE_AUTH_MODE === 'entra') {
      try { foundryToken = await getFoundryToken() }
      catch (e: any) { return res.status(500).json({ error: 'Could not obtain Entra token for Foundry: ' + (e?.message || e) }) }
    }

    const envVars: Record<string, string> = {}
    // OpenCode reads these for the azure provider auth.
    if (AZURE_AUTH_MODE === 'apikey') {
      if (!AZURE_API_KEY) return res.status(500).json({ error: 'AZURE_AUTH_MODE=apikey but AZURE_API_KEY is not set.' })
      envVars.AZURE_API_KEY = AZURE_API_KEY
    } else {
      // Bearer token from managed identity. OpenCode/AI-SDK can send it via the
      // azure provider's token path; we also export it for the config to read.
      envVars.AZURE_FOUNDRY_TOKEN = foundryToken
    }
    if (AZURE_FOUNDRY_BASE_URL) envVars.AZURE_FOUNDRY_BASE_URL = AZURE_FOUNDRY_BASE_URL
    if (AZURE_API_VERSION) envVars.AZURE_API_VERSION = AZURE_API_VERSION

    const labels: Record<string, string> = { app: APP_LABEL }
    if (wantedName) labels.name = wantedName

    console.log('[launch] creating sandbox%s ...', wantedName ? ` "${wantedName}"` : '')
    sandbox = await daytona.create(
      { image: SANDBOX_IMAGE, public: true, labels, envVars, resources: { cpu: 1, memory: 2, disk: 5 } },
      { timeout: 180 },
    )

    console.log('[launch] installing OpenCode...')
    await sandbox.process.executeCommand(`npm i -g opencode-ai@${OPENCODE_VERSION}`)

    // Preview URL pattern for the agent prompt.
    const previewLink = await sandbox.getPreviewLink(1234)
    const previewUrlPattern = previewLink.url.replace(/1234/, '{PORT}')

    const systemPrompt = [
      'You are running in a Daytona sandbox for an internal firm tool.',
      'Use the /home/daytona directory for file operations.',
      'This sandbox is reachable on the firm network; every port you expose has a preview URL of this form (replace {PORT}): ' + previewUrlPattern,
      'Bind servers to 0.0.0.0 and start them in the background with & , then print the preview URL for that port.',
      'git is available for local version control.',
    ].join(' ')

    // Build the OpenCode config: prefer the committed opencode.json, else assemble
    // an Azure Foundry config from env. Always set the daytona agent + default model.
    const fileCfg = loadOpencodeConfig()
    const opencodeConfig: any = fileCfg ? JSON.parse(JSON.stringify(fileCfg)) : { $schema: 'https://opencode.ai/config.json' }
    // Ensure default model + a sandbox-aware agent are present.
    if (!opencodeConfig.model && AZURE_DEFAULT_DEPLOYMENT) {
      opencodeConfig.model = 'azure/' + AZURE_DEFAULT_DEPLOYMENT
    }
    opencodeConfig.default_agent = 'daytona'
    opencodeConfig.agent = opencodeConfig.agent || {}
    opencodeConfig.agent.daytona = {
      description: 'Daytona sandbox-aware coding agent (Azure Foundry)',
      mode: 'primary',
      model: opencodeConfig.model || ('azure/' + AZURE_DEFAULT_DEPLOYMENT),
      prompt: systemPrompt,
    }

    const configJson = JSON.stringify(opencodeConfig)
    const b64 = Buffer.from(configJson).toString('base64')
    const envVar = `OPENCODE_CONFIG_CONTENT=$(echo '${b64}' | base64 -d)`

    const sessionId = `opencode-session-${Date.now()}`
    await sandbox.process.createSession(sessionId)

    // git available + identity (no GitHub account wiring — accountants don't ship code).
    await sandbox.process.executeCommand(
      `(command -v git >/dev/null 2>&1 || (apt-get update -qq && apt-get install -y -qq git >/dev/null 2>&1)); ` +
        `git config --global user.name "OpenCode"; git config --global user.email "opencode@firm.local"; ` +
        `git config --global init.defaultBranch main; git config --global --add safe.directory '*'; true`,
      undefined, undefined, 180,
    )

    // Warm up the SQLite DB (apply migrations) before the web server starts.
    console.log('[launch] warming up OpenCode DB...')
    try {
      await sandbox.process.executeCommand(
        `mkdir -p /home/daytona; cd /home/daytona; ${envVar} opencode run -m ${opencodeConfig.model} "ready" >/tmp/warmup.log 2>&1; true`,
        undefined, undefined, 120,
      )
    } catch (e: any) { console.warn('[launch] warmup non-fatal:', e?.message || e) }

    await sandbox.process.executeSessionCommand(sessionId, {
      command: `${envVar} opencode web --hostname 0.0.0.0 --port ${OPENCODE_PORT}`,
      runAsync: true,
    })

    const opencodePreviewLink = await sandbox.getPreviewLink(OPENCODE_PORT)
    const sandboxId = (sandbox as any).id ?? (sandbox as any).sandboxId ?? 'unknown'

    // Readiness: inside (port bound) then outside (proxy live).
    let webReady = false
    for (let i = 0; i < 20; i++) {
      try {
        const probe = await sandbox.process.executeCommand(
          `curl -s -o /dev/null -w "%{http_code}" --max-time 4 http://127.0.0.1:${OPENCODE_PORT}/ 2>/dev/null || echo 000`,
          undefined, undefined, 15,
        )
        if (String((probe as any).result || '').trim().split('\n').pop() === '200') { webReady = true; break }
      } catch {}
      await new Promise((r) => setTimeout(r, 2000))
    }
    let publicReady = false
    for (let i = 0; i < 20; i++) {
      try {
        const ctl = new AbortController(); const t = setTimeout(() => ctl.abort(), 6000)
        const r = await fetch(opencodePreviewLink.url, { method: 'GET', redirect: 'manual', signal: ctl.signal })
        clearTimeout(t)
        if (r.status === 200 || (r.status >= 300 && r.status < 400)) { publicReady = true; break }
      } catch {}
      await new Promise((r) => setTimeout(r, 2000))
    }

    sandboxes.set(sandboxId, { url: opencodePreviewLink.url, createdAt: new Date().toISOString(), name: wantedName || undefined })
    console.log('[launch] ready: %s (sandbox=%s)', opencodePreviewLink.url, sandboxId)
    return res.json({ ok: true, sandboxId, name: wantedName || undefined, url: opencodePreviewLink.url, webReady, publicReady })
  } catch (err: any) {
    console.error('[launch] error:', err?.message || err)
    try { if (sandbox) await sandbox.delete() } catch {}
    return res.status(500).json({ error: String(err?.message || err) })
  }
})

