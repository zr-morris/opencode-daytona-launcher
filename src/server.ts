app.get('/login', (req: Request, res: Response) => {
  if (!SSO_ENABLED) return res.redirect('/')
  if (getSession(req)) return res.redirect('/')
  const err = typeof req.query.error === 'string' ? req.query.error : ''
  res.type('html').send(loginPage(err))
})

app.get('/auth/login', async (req: Request, res: Response) => {
  if (!SSO_ENABLED || !msal) return res.redirect('/')
  const state = b64url(crypto.randomBytes(16))
  res.setHeader('Set-Cookie', `${OAUTH_STATE_COOKIE}=${state}; HttpOnly; Secure; SameSite=Lax; Path=/; Max-Age=600`)
  try {
    const url = await msal.getAuthCodeUrl({
      scopes: ['openid', 'profile', 'email', 'User.Read'],
      redirectUri: `${baseUrl(req)}/auth/callback`,
      state,
    })
    res.redirect(url)
  } catch (e: any) {
    res.redirect('/login?error=' + encodeURIComponent('Could not start sign-in: ' + (e?.message || e)))
  }
})

app.get('/auth/callback', async (req: Request, res: Response) => {
  if (!SSO_ENABLED || !msal) return res.redirect('/')
  const code = typeof req.query.code === 'string' ? req.query.code : ''
  const state = typeof req.query.state === 'string' ? req.query.state : ''
  const cookieState = parseCookies(req)[OAUTH_STATE_COOKIE] || ''
  if (!code || !state || state !== cookieState) {
    return res.redirect('/login?error=' + encodeURIComponent('Sign-in failed (state mismatch). Please try again.'))
  }
  try {
    const result = await msal.acquireTokenByCode({
      code,
      scopes: ['openid', 'profile', 'email', 'User.Read'],
      redirectUri: `${baseUrl(req)}/auth/callback`,
    })
    const acct = result?.account
    const claims: any = (result as any)?.idTokenClaims || {}
    const oid = acct?.homeAccountId || claims.oid || claims.sub || 'unknown'
    const name = acct?.name || claims.name
    const email = claims.preferred_username || claims.email || acct?.username
    const sess: Session = { oid, name, email, exp: Date.now() + SESSION_TTL_MS }
    setSessionCookie(res, signSession(sess))
    res.append('Set-Cookie', `${OAUTH_STATE_COOKIE}=; HttpOnly; Secure; SameSite=Lax; Path=/; Max-Age=0`)
    console.log('[auth] sign-in ok: %s', email || oid)
    res.redirect('/')
  } catch (e: any) {
    res.redirect('/login?error=' + encodeURIComponent('Sign-in error: ' + (e?.message || e)))
  }
})

app.post('/auth/logout', (_req: Request, res: Response) => { clearSessionCookie(res); res.json({ ok: true }) })
app.get('/auth/logout', (_req: Request, res: Response) => { clearSessionCookie(res); res.redirect('/login') })

